#!/usr/bin/env bash
# Build + QA + render only some pages, in a private "lane", so parallel sessions never share out/, renders/ or the
# LibreOffice profile. The lane links to this deck's slides/, assets/ and theme.js, so nothing is copied.
#
#   ./lane.sh <lane> S13,S14,S15            # → _lanes/<lane>/renders/S13.png … and _lanes/<lane>/renders/_contact.png
#   ./lane.sh <lane> S13 --no-render        # build + QA only
#   ./lane.sh <lane> S12,S13 --only S13     # neighbours for Morph context, render just S13
set -euo pipefail
DECK="$(cd "$(dirname "$0")" && pwd)"
LANE="${1:?usage: ./lane.sh <lane> S13,S14 [make.js options]}"
IDS="${2:?usage: ./lane.sh <lane> S13,S14 [make.js options]}"
shift 2
L="$DECK/_lanes/$LANE"
mkdir -p "$L/.tmp"
ln -sfn ../../slides "$L/slides"
ln -sfn ../../assets "$L/assets"
node -e '
const [lane, ids] = process.argv.slice(1);
const slides = ids.split(",").map((s) => s.trim()).filter(Boolean);
process.stdout.write(`// generated by lane.sh — do not edit\nmodule.exports = ${JSON.stringify({ name: `lane-${lane}`, title: `lane ${lane}`, theme: "../../theme.js", slides }, null, 2)};\n`);
' "$LANE" "$IDS" > "$L/deck.js"
TMPDIR="$L/.tmp" node "$DECK/../../engine/make.js" "$L" "$@"
